#!/usr/bin/env python3
"""Generate the Gazebo world and the Nav2 map from a world file.

One file, robotics/worlds/workcell.json, describes the room. HANNAH's built-in
simulator reads it directly. This tool writes the same room as:

  ros2_ws/src/hannah_sim/worlds/<name>.sdf   a Gazebo (SDFormat 1.9) world
  ros2_ws/src/hannah_sim/maps/<name>.pgm     an occupancy map for Nav2's map server
  ros2_ws/src/hannah_sim/maps/<name>.yaml    its metadata

so the two simulators and the navigation map can't drift apart. Run it after
changing the world file; a test checks that the committed files are current.

    python3 tools/build_world.py            # write the files
    python3 tools/build_world.py --check    # exit 1 if they are out of date
"""
from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PACKAGE = os.path.join(ROOT, "ros2_ws", "src", "hannah_sim")
RESOLUTION = 0.05


def box(name: str, x: float, y: float, w: float, h: float, height: float, colour: str) -> str:
    cx, cy = x + w / 2, y + h / 2
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{cx:.3f} {cy:.3f} {height / 2:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{w:.3f} {h:.3f} {height:.3f}</size></box></geometry></collision>
        <visual name="visual">
          <geometry><box><size>{w:.3f} {h:.3f} {height:.3f}</size></box></geometry>
          <material><ambient>{colour} 1</ambient><diffuse>{colour} 1</diffuse></material>
        </visual>
      </link>
    </model>
"""


def sdf(world: dict) -> str:
    b = world["bounds"]
    t = float(world.get("wallThickness", 0.15))
    wall_height = float(world.get("wallHeight", 1.0))
    width, depth = b["maxX"] - b["minX"], b["maxY"] - b["minY"]
    walls = [
        ("wall_south", b["minX"] - t, b["minY"] - t, width + 2 * t, t),
        ("wall_north", b["minX"] - t, b["maxY"], width + 2 * t, t),
        ("wall_west", b["minX"] - t, b["minY"], t, depth),
        ("wall_east", b["maxX"], b["minY"], t, depth),
    ]
    models = "".join(box(name, x, y, w, h, wall_height, "0.75 0.75 0.75") for name, x, y, w, h in walls)
    models += "".join(box(o["name"], o["x"], o["y"], o["w"], o["h"], float(o.get("height", 1.0)), "0.45 0.5 0.6") for o in world["obstacles"])
    return f"""<?xml version="1.0"?>
<!-- Generated by robotics/tools/build_world.py from robotics/worlds/{world["name"]}.json. Do not edit by hand. -->
<sdf version="1.9">
  <world name="{world["name"]}">
    <physics name="1ms" type="ignored"><max_step_size>0.001</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows><pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse><specular>0.2 0.2 0.2 1</specular><direction>-0.4 0.2 -0.9</direction>
    </light>
    <model name="floor">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>{width + 4:.1f} {depth + 4:.1f}</size></plane></geometry></collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>{width + 4:.1f} {depth + 4:.1f}</size></plane></geometry>
          <material><ambient>0.9 0.9 0.9 1</ambient><diffuse>0.9 0.9 0.9 1</diffuse></material>
        </visual>
      </link>
    </model>
{models}  </world>
</sdf>
"""


def occupancy(world: dict) -> tuple[bytes, int, int]:
    """A PGM (P5) image: 0 occupied, 254 free. Row 0 is the top (maxY), as Nav2's map server expects."""
    b = world["bounds"]
    t = float(world.get("wallThickness", 0.15))
    min_x, min_y = b["minX"] - t, b["minY"] - t
    cols = int(round((b["maxX"] - b["minX"] + 2 * t) / RESOLUTION))
    rows = int(round((b["maxY"] - b["minY"] + 2 * t) / RESOLUTION))
    pixels = bytearray()
    for row in range(rows):
        y = min_y + (rows - row - 0.5) * RESOLUTION
        for col in range(cols):
            x = min_x + (col + 0.5) * RESOLUTION
            outside = x < b["minX"] or x > b["maxX"] or y < b["minY"] or y > b["maxY"]
            inside = any(o["x"] <= x <= o["x"] + o["w"] and o["y"] <= y <= o["y"] + o["h"] for o in world["obstacles"])
            pixels.append(0 if outside or inside else 254)
    return f"P5\n{cols} {rows}\n255\n".encode("ascii") + bytes(pixels), cols, rows


def map_yaml(world: dict) -> str:
    b = world["bounds"]
    t = float(world.get("wallThickness", 0.15))
    return (
        f"# Generated by robotics/tools/build_world.py from robotics/worlds/{world['name']}.json. Do not edit by hand.\n"
        f"image: {world['name']}.pgm\nmode: trinary\nresolution: {RESOLUTION}\n"
        f"origin: [{b['minX'] - t:.3f}, {b['minY'] - t:.3f}, 0.0]\nnegate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.25\n"
    )


def outputs(world: dict) -> dict[str, bytes]:
    image, _, _ = occupancy(world)
    name = world["name"]
    return {
        os.path.join(PACKAGE, "worlds", f"{name}.sdf"): sdf(world).encode("utf-8"),
        os.path.join(PACKAGE, "maps", f"{name}.pgm"): image,
        os.path.join(PACKAGE, "maps", f"{name}.yaml"): map_yaml(world).encode("utf-8"),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--world", default=os.path.join(ROOT, "worlds", "workcell.json"))
    parser.add_argument("--check", action="store_true", help="Don't write; exit 1 if a generated file is missing or out of date.")
    args = parser.parse_args(argv)
    with open(args.world, "r", encoding="utf-8") as handle:
        world = json.load(handle)
    stale = []
    for path, content in outputs(world).items():
        current = None
        if os.path.exists(path):
            with open(path, "rb") as handle:
                current = handle.read()
        if current == content:
            continue
        if args.check:
            stale.append(os.path.relpath(path, ROOT))
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as handle:
            handle.write(content)
        print(f"wrote {os.path.relpath(path, ROOT)}")
    if stale:
        print("Out of date (run python3 tools/build_world.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
